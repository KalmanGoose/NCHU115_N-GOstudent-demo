    if street_name and "校內" not in street_name:
        query += f" {street_name.split('/')[0]}"

    try:
        q = urllib.parse.quote(query)
        url = f"https://www.bing.com/images/async?q={q}&first=1&count=8"
        req = urllib.request.Request(url, headers=HEADERS)
        with urllib.request.urlopen(req, timeout=3) as r:
            html = r.read().decode("utf-8", errors="ignore")
            murls = re.findall(r'murl&quot;:&quot;(https?://[^&]+)&quot;', html)
            for m in murls:
                if not any(bad in m.lower() for bad in ['.svg', 'logo', 'avatar', 'placeholder', 'favicon', 'icon']):
                    return m
            if murls:
                return murls[0]
    except Exception:
        pass

    return ""


