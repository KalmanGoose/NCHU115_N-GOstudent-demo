def load_all_stores() -> List[Dict[str, str]]:
    """
    安全讀取 Dcard 既有 176 筆資料庫，並聚合新增的實體商圈店家
    """
    stores = []
    seen_names = set()

    # 1. 完整讀取 Dcard 既有資料庫 (176 筆)
    if os.path.exists(DCARD_JS_PATH):
        with open(DCARD_JS_PATH, "r", encoding="utf-8") as f:
            text = f.read()
        items = re.findall(r'\{\s*"title":\s*"(.*?)",\s*"content":\s*"(.*?)"', text, re.DOTALL)
        for t, c in items:
            clean_name = re.sub(r'\(.*?\)', '', t).strip()
            if clean_name and clean_name not in seen_names:
                seen_names.add(clean_name)
                stores.append({
                    "name": t.strip(),
                    "content": c.strip(),
                    "source": "Dcard學長姐推薦"
                })

    # 2. 增量合併生活圈擴充庫
    for item in EXPANDED_ZONE_DATABASE:
        clean_item_name = re.sub(r'\(.*?\)', '', item["name"]).strip()
        if clean_item_name not in seen_names and item["name"] not in seen_names:
            seen_names.add(item["name"])
            stores.append({
                "name": item["name"].strip(),
                "content": item["content"].strip(),
                "source": "生活圈實體擴充"
            })

    return stores


