def load_photo_cache() -> Dict[str, str]:
    """
    載入既有抓取成功的 287 家真實美食照片快取，避免重複爬取浪費時間
    """
    cache = {}
    if os.path.exists(OUTPUT_CSV):
        try:
            with open(OUTPUT_CSV, "r", encoding="utf-8-sig") as f:
                reader = csv.DictReader(f)
                for r in reader:
                    url = r.get("photo_url", "")
                    if url and "unsplash" not in url:
                        name_key = re.sub(r'\(.*?\)', '', r.get("name", "")).strip()
                        cache[name_key] = url
                        cache[r.get("name", "").strip()] = url
        except Exception:
            pass
    return cache


