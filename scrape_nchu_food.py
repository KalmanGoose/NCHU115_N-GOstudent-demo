def resolve_real_address(name: str, content: str) -> str:
    """
    精確解析店家的真實物理門牌地址。
    1. 優先查核高精準地址總表 EXACT_STORE_ADDRESSES。
    2. 從內文 content 提取含有真實門牌的段落。
    3. 絕不使用 hash() 捏造門牌號碼！
    """
    clean_name = re.sub(r'\(.*?\)', '', name).strip()

    # 1. 精確字典匹配 (優先全名匹配，如區分興大忠明南店與興大學府店)
    if name in EXACT_STORE_ADDRESSES:
        return EXACT_STORE_ADDRESSES[name]
    if clean_name in EXACT_STORE_ADDRESSES:
        return EXACT_STORE_ADDRESSES[clean_name]

    # 模糊字典匹配
    for key, addr in EXACT_STORE_ADDRESSES.items():
        if key in clean_name or clean_name in key:
            return addr

    # 2. 檢測 content 內是否已寫入地址段落 (如【學府路137號...】或【地址:台中市...】)
    m = re.search(r'(台中市[^\s，。、（）「」【】\n\r]{4,35}(?:號|樓|巷|街|路))', content)
    if m:
        return m.group(1)

    m2 = re.search(r'【([^\s/，。、（）「」【】\n\r]{2,15}(?:路|街|巷)[0-9號之\-]+)', content)
    if m2:
        street_str = m2.group(1)
        if not street_str.startswith("台中市"):
            street_str = f"台中市南區{street_str}"
        return street_str

    # 3. 嚴格回退：若無精確門牌，按內文商圈給予確切街道（不偽造假門牌號碼）
    if "南門路" in content or "女宿" in content:
        return "台中市南區南門路"
    elif "學府路" in content or "大門" in content:
        return "台中市南區學府路"
    elif "忠孝" in content:
        return "台中市南區忠孝路"
    elif "高工路" in content:
        return "台中市南區高工路"
    elif "美村南路" in content:
        return "台中市南區美村南路"
    elif "工學路" in content:
        return "台中市南區工學路"
    elif "大明路" in content:
        return "台中市大里區大明路"

    return "台中市南區興大路145號 (興大校園周邊)"


