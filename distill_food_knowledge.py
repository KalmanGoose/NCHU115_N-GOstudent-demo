def distill_and_merge():
    print("\n" + "="*70)
    print(" 🍜 啟動中興大學周邊美食與生活筆記知識蒸餾管線")
    print("="*70)

    # 1. 讀取現有知識庫
    if not os.path.exists(JSON_PATH):
        print(f"❌ 找不到知識庫檔案: {JSON_PATH}")
        return

    with open(JSON_PATH, "r", encoding="utf-8") as f:
        existing_data = json.load(f)

    print(f"📥 目前 campus_knowledge.json 包含: {len(existing_data)} 筆條目")

    master_map: Dict[str, Dict[str, Any]] = {}
    for it in existing_data:
        name = it.get("名稱") or it.get("name") or ""
        master_map[name] = it

    # 2. 合併新蒸餾之美食資料
    added_count = 0
    updated_count = 0

    for item in RAW_FOOD_ITEMS:
        name = item["name"]
        kws = item["kws"]
        content = item["content"]

        if name not in master_map:
            master_map[name] = {
                "關鍵字": ",".join(kws),
                "名稱": name,
                "情報內容": content,
                "direct": True
            }
            added_count += 1
        else:
            # 合併關鍵字與內容
            old_kws = master_map[name].get("關鍵字", "").split(",")
            merged_kws = list(set([k.strip() for k in old_kws + kws if k.strip()]))
            master_map[name]["關鍵字"] = ",".join(merged_kws)
            master_map[name]["情報內容"] = content
            master_map[name]["direct"] = True
            updated_count += 1

    final_list = list(master_map.values())
    total_count = len(final_list)

    print(f"✨ 蒸餾完成！新增 {added_count} 筆新美食條目，更新 {updated_count} 筆現有條目。")
    print(f"🎉 知識庫總條目數擴充至: {total_count} 筆！")

    # 3. 覆寫 1: campus_knowledge.json (UTF-8)
    print(f"\n💾 1. 正在更新 {JSON_PATH} ...")
    with open(JSON_PATH, "w", encoding="utf-8") as f:
        json.dump(final_list, f, ensure_ascii=False, indent=2)
    print(f"  ✅ campus_knowledge.json 更新完成！({total_count} 筆)")

    # 4. 覆寫 2: campus_knowledge.csv (UTF-8 with BOM)
    print(f"💾 2. 正在更新 {CSV_PATH} ...")
    with open(CSV_PATH, "w", encoding="utf-8-sig", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=["關鍵字", "名稱", "情報內容", "direct"])
        writer.writeheader()
        for it in final_list:
            writer.writerow({
                "關鍵字": it.get("關鍵字", ""),
                "名稱": it.get("名稱", ""),
                "情報內容": it.get("情報內容", ""),
                "direct": "true" if it.get("direct") else "false"
            })
    print(f"  ✅ campus_knowledge.csv 更新完成！({total_count} 筆)")

    # 5. 覆寫 3: KnowledgeData.gs (var CAMPUS_KNOWLEDGE = [ ... ];)
    print(f"💾 3. 正在更新 {GS_PATH} ...")
    gs_items = []
    for it in final_list:
        kws_list = [k.strip() for k in it.get("關鍵字", "").split(",") if k.strip()]
        gs_items.append({
            "keywords": kws_list,
            "name": it.get("名稱", ""),
            "content": it.get("情報內容", ""),
            "direct": bool(it.get("direct", False))
        })

    gs_header = "/**\n * ==============================================================================\n * 國立中興大學 (NCHU) 全校園知識庫靜態常數資料 (KnowledgeData.gs)\n * 本檔案由 distill_food_knowledge.py 自動整合，包含全校美食地圖與各類校園知識。\n * 總條目數: " + str(total_count) + " 筆\n * ==============================================================================\n */\n\n"
    gs_content = gs_header + "var CAMPUS_KNOWLEDGE = " + json.dumps(gs_items, ensure_ascii=False, indent=2) + ";\n"
    with open(GS_PATH, "w", encoding="utf-8") as f:
        f.write(gs_content)
    print(f"  ✅ KnowledgeData.gs 更新完成！({total_count} 筆)")

    print("\n" + "="*70)
    print(f" 🏆 美食蒸餾與合併作業成功完成！總知識庫規模: {total_count} 筆。")
    print("="*70)

if __name__ == "__main__":
    distill_and_merge()
