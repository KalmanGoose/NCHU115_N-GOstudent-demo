def generate_v2_instruct(knowledge_base):
    print("🌲 生成高品質無模板 Qwen2.5-3B SFT 對齊資料集...")
    all_conversations = list(REAL_CONVERSATIONS)

    # 針對知識庫中的高品質條目，合成多樣化問答對（嚴格禁止固定模板開頭！）
    for item in knowledge_base:
        name = item.get("名稱", "")
        content = item.get("情報內容", "")
        if len(content) < 60:
            continue

        keywords = [k.strip() for k in item.get("關鍵字", "").split(",") if len(k.strip()) >= 2]
        kw = keywords[0] if keywords else name

        user_queries = [
            f"請問中興大學關於「{kw}」有什麼具體規定？",
            f"我想了解「{name}」，可以幫我說明重點嗎？",
            f"大一新生想請問{kw}的注意事項是什麼？"
        ]
        user_q = random.choice(user_queries)

        # 多樣化的自然學長姐開頭
        openers = [
            f"關於你問的【{name}】，學長姐幫你把學校官方規定的重點整理在下面：\n\n",
            f"收到！針對「{kw}」，這個常常有學弟妹搞不清楚，具體規則是這樣：\n\n",
            f"這題很重要喔！關於【{name}】的官方規範如下：\n\n",
            f"沒問題，在中興生活一定要知道這個！關於【{name}】：\n\n"
        ]
        closers = [
            "\n\n記得要以學校最新公告為準，有不懂的隨時再問我喔！🌲",
            "\n\n照著上面步驟辦理基本上就沒問題了，祝你大學生活順利！✨",
            "\n\n重要手續記得提早跑流程，千萬別拖到最後一天截止日喔！💪",
            "\n\n如果還有疑問也可以直接打電話去負責的處室詢問，加油！🎓"
        ]

        assistant_a = random.choice(openers) + content + random.choice(closers)

        all_conversations.append({
            "messages": [
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": user_q},
                {"role": "assistant", "content": assistant_a}
            ]
        })

    # 切分訓練集與驗證集 (90% train, 10% eval)
    random.shuffle(all_conversations)
    split_idx = int(len(all_conversations) * 0.9)
    train_convs = all_conversations[:split_idx]
    eval_convs = all_conversations[split_idx:]

    with open(INSTRUCT_OUTPUT, "w", encoding="utf-8") as f:
        for c in train_convs:
            f.write(json.dumps(c, ensure_ascii=False) + "\n")

    with open(EVAL_INSTRUCT_OUTPUT, "w", encoding="utf-8") as f:
        for c in eval_convs:
            f.write(json.dumps(c, ensure_ascii=False) + "\n")

    print(f"✅ 生成微調訓練集: {len(train_convs)} 筆 -> {INSTRUCT_OUTPUT}")
    print(f"✅ 生成微調驗證集: {len(eval_convs)} 筆 -> {EVAL_INSTRUCT_OUTPUT}")

