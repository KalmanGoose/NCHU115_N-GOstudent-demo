def clean_str(val: Any) -> str:
    if val is None:
        return ""
    v = str(val).strip()
    if v.lower() in ("nan", "none", "null", "undefined"):
        return ""
    return v

def clean_teacher_name(t_raw: str) -> str:
    t = clean_str(t_raw)
    t = re.sub(r'老師|教授|（歷史系）|\(歷史系\)|兼任|專任', '', t).strip()
    return t

def format_score(val: Any, label: str) -> str:
    v = clean_str(val)
    if not v:
        return ""
    try:
        f = float(v)
        if f.is_integer():
            return f"{label}:{int(f)}/5"
        return f"{label}:{f}/5"
    except ValueError:
        return f"{label}:{v}/5"

