def parse_freshman_knowledge_gs() -> List[Dict[str, Any]]:
    """解析手動維護之 FreshmanKnowledge.gs 檔案"""
    if not os.path.exists(FRESHMAN_GS_PATH):
        return []
    
    items = []
    try:
        with open(FRESHMAN_GS_PATH, "r", encoding="utf-8") as f:
            text = f.read()

        match = re.search(r'var\s+FRESHMAN_KNOWLEDGE\s*=\s*\[([\s\S]*?)\]\s*;', text)
        if match:
            content = match.group(1)
            obj_blocks = re.findall(r'\{([^{}]*(?:\{[^{}]*\}[^{}]*)*)\}', content)
            for block in obj_blocks:
                name_m = re.search(r'\"name\"\s*:\s*\"([^\"]+)\"', block)
                content_m = re.search(r'\"content\"\s*:\s*\"((?:\\.|[^\"])*)\"', block)
                kw_m = re.search(r'\"keywords\"\s*:\s*\[([\s\S]*?)\]', block)
                
                name = name_m.group(1) if name_m else ''
                c_raw = content_m.group(1) if content_m else ''
                c = c_raw.replace('\\n', '\n').replace('\\"', '"').replace('\\\\', '\\')
                
                kws = []
                if kw_m:
                    kws = re.findall(r'\"([^\"]+)\"', kw_m.group(1))
                    
                direct_m = re.search(r'"direct"\s*:\s*(true|false)', block)
                is_direct = (direct_m.group(1) == 'true') if direct_m else False
                if name and c:
                    items.append({'name': name, 'keywords': kws, 'content': c, 'direct': is_direct})
    except Exception as e:
        print(f"⚠️ 解析 FreshmanKnowledge.gs 異常: {e}")
    return items

